function lookupAlias(aliases: Record<string, DeviceAlias> | undefined, mac?: string, ip?: string): DeviceAlias | undefined {
  if (!aliases) return undefined;
  const key = normalizeMacKey(mac, ip);
  if (key && aliases[key]) return aliases[key];
  if (ip) {
    const ipKey = `IP:${ip.trim()}`;
    if (aliases[ipKey]) return aliases[ipKey];
  }
  return undefined;
}

function computeRiskLevel(openPorts: number[]): { riskLevel: 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW'; highRiskPorts: number[] } {
  const highRiskPorts = openPorts.filter((p) => Boolean(HIGH_RISK_PORT_RULES[p]));
  if (highRiskPorts.some((p) => HIGH_RISK_PORT_RULES[p]?.severity === 'CRITICAL')) {
    return { riskLevel: 'CRITICAL', highRiskPorts };
  }
  if (highRiskPorts.some((p) => HIGH_RISK_PORT_RULES[p]?.severity === 'HIGH')) {
    return { riskLevel: 'HIGH', highRiskPorts };
  }
  if (highRiskPorts.length > 0) {
    return { riskLevel: 'MEDIUM', highRiskPorts };
  }
  return { riskLevel: 'LOW', highRiskPorts };
}

export function buildPreparedReportDataset(input: BuildDatasetInput): PreparedReportDataset {
  const {
    scope,
    sortBy,
    sortDir,
    subnet,
    start,
    end,
    allIps,
    filteredIps,
    searchQuery,
    results,
    aliases,
    license,
    branding,
    baselineSnapshot = null,
    includeDiffSection = true,
    scanStartTimestamp = null,
    scanEndTimestamp = null,
    totalScanDurationMs = 0,
    totalScannedIpCount,
    isScanning = false,
    lang = 'ko',
    s,
  } = input;

  const isKo = lang === 'ko';
  const now = new Date();
  const activeResults = allIps.filter((ip) => results[ip]?.status === 'active');
  const totalDeviceCount = Math.max(allIps.length, activeResults.length, Math.max(0, end - start + 1));

  const scannedInGrid = allIps.filter((ip) => {
    const st = results[ip]?.status;
    return st === 'active' || st === 'inactive';
  }).length;
  const resolvedScannedIps = Math.max(
    activeResults.length,
    typeof totalScannedIpCount === 'number' && Number.isFinite(totalScannedIpCount)
      ? Math.max(0, Math.round(totalScannedIpCount))
      : scannedInGrid > 0
      ? scannedInGrid
      : totalDeviceCount
  );

  const gates = resolveFeatureGates(license);
  const rawEffectiveBranding = gates.reportBrandingLogo ? branding : getDefaultBranding(lang);
  const safeLogoUrl = sanitizeImageDataUrl(rawEffectiveBranding.logoDataUrl);
  const effectiveBranding: ReportBrandingConfig = {
    ...rawEffectiveBranding,
    accentColor: sanitizeHexColor(rawEffectiveBranding.accentColor, '#0284c7'),
    logoDataUrl: safeLogoUrl || undefined,
  };

  // Compute Snapshot Diff if baseline is available and licensed (PRO+)
  let diffAnalysis: DiffAnalysisResult | null = null;
  const diffItemByIp: Record<string, DiffItem> = {};
  if (gates.reportDiffCompare && baselineSnapshot && (includeDiffSection || scope === 'diff')) {
    diffAnalysis = computeSnapshotDiff(
      results,
      baselineSnapshot.results,
      isKo ? '현재 스캔' : 'Current Scan',
      baselineSnapshot.label
    );
    diffAnalysis.items.forEach((item) => {
      diffItemByIp[item.ip] = item;
    });
  }

  // Vendor & Risk Analytics across all active nodes
  const vendorCounts: Record<string, number> = {};
  let totalOpenPorts = 0;
  const highRiskAlerts: HighRiskAlertItem[] = [];

  activeResults.forEach((ip) => {
    const dev = results[ip]?.device;
    const v = dev?.realVendor || dev?.vendor || 'Unknown Vendor';
    vendorCounts[v] = (vendorCounts[v] || 0) + 1;
    const ports = dev?.openPorts || [];
    totalOpenPorts += ports.length;
    ports.forEach((p) => {
      const rule = HIGH_RISK_PORT_RULES[p];
      if (rule) {
        highRiskAlerts.push({
          ip,
          port: p,
          name: rule.name,
          severity: rule.severity,
          threat: isKo ? rule.threatKo : rule.threatEn,
          remediation: isKo ? rule.remediationKo : rule.remediationEn,
        });
      }
    });
  });

  const vendorBreakdown = Object.entries(vendorCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([vendor, count]) => ({
      vendor,
      count,
      sharePct: activeResults.length > 0 ? ((count / activeResults.length) * 100).toFixed(1) : '0.0',
    }));

  // Determine Target IP List for the selected scope
  let scopeIps: string[] = [];
  if (scope === 'active' || scope === 'audit' || scope === 'summary') {
    scopeIps = activeResults;
  } else if (scope === 'search') {
    scopeIps = filteredIps && filteredIps.length > 0 ? filteredIps : searchQuery ? [] : allIps;
  } else if (scope === 'diff') {
    if (diffAnalysis) {
      const changed = diffAnalysis.items.filter((i) => i.diffStatus !== 'same');
      scopeIps = (changed.length > 0 ? changed : diffAnalysis.items).map((i) => i.ip);
    } else {
      scopeIps = activeResults;
    }
  } else {
    scopeIps = allIps;
  }

  // Construct enriched rows
  const rows: PreparedDeviceRow[] = scopeIps.map((ip) => {
    const curResult = results[ip];
    const diffEntry = diffItemByIp[ip];
    // For offline devices in diff mode, display last-known device details from previous snapshot if current is inactive
    const effectiveDevice = curResult?.device || (diffEntry?.diffStatus === 'offline' ? diffEntry.previous?.device : undefined);
    const status = curResult?.status || (diffEntry?.diffStatus === 'offline' ? 'offline' : 'idle');
    const ports = effectiveDevice?.openPorts || [];
    const { riskLevel, highRiskPorts } = computeRiskLevel(ports);
    const classification = effectiveDevice
      ? classifyDeviceHybrid(effectiveDevice.vendor || '', ports, s, {
          ip,
          hostname: effectiveDevice.hostname,
          mdns: effectiveDevice.mdns,
          webTitle: effectiveDevice.webTitle,
          upnp: effectiveDevice.upnp,
          snmp: effectiveDevice.snmp,
          mac: effectiveDevice.mac,
          realVendor: effectiveDevice.realVendor,
          chipsetVendor: effectiveDevice.chipsetVendor,
          vendorSource: effectiveDevice.vendorSource,
          ouiBlockType: effectiveDevice.ouiBlockType,
          ouiPrefix: effectiveDevice.ouiPrefix,
          isRandomizedMac: effectiveDevice.isRandomizedMac,
          lang,
        })
      : null;

    const aliasObj = lookupAlias(aliases, effectiveDevice?.mac, ip);
    const aliasNickname = aliasObj?.nickname || effectiveDevice?.customNickname || '';
    const aliasNotes = aliasObj?.notes || effectiveDevice?.notes || '';
    const aliasText = [aliasNickname, aliasNotes].filter(Boolean).join(' · ');

    const primaryVendor = effectiveDevice?.realVendor && effectiveDevice.realVendor !== effectiveDevice.vendor
      ? `${effectiveDevice.realVendor} (${effectiveDevice.vendor})`
      : effectiveDevice?.vendor || (status === 'active' ? 'Unknown' : '-');

    return {
      ip,
      lastOctet: ipLastOctet(ip),
      status,
      mac: effectiveDevice?.mac || '-',
      vendor: primaryVendor,
      chipsetVendor: effectiveDevice?.chipsetVendor || effectiveDevice?.vendor || '-',
      hostname: effectiveDevice?.hostname || '-',
      webTitle: effectiveDevice?.webTitle,
      nameSource: effectiveDevice?.nameSource || 'UNKNOWN',
      latency: status === 'active' ? (effectiveDevice?.latency ?? 0) : null,
      openPorts: ports,
      deviceType: classification?.type || '-',
      os: classification?.os || '-',
      deviceModel: effectiveDevice?.deviceModel || classification?.model,
      aliasNickname,
      aliasNotes,
      aliasText: aliasText || '-',
      riskLevel,
      highRiskPorts,
      diffStatus: diffEntry?.diffStatus,
      diffDetails: diffEntry?.changeDetails,
      hasSecurityRisk: diffEntry?.hasSecurityRisk || highRiskPorts.length > 0,
      isConflict: Boolean(curResult?.isConflict || effectiveDevice?.isConflict),
    };
  });

  // Sort rows cleanly
  const riskRank: Record<PreparedDeviceRow['riskLevel'], number> = {
    CRITICAL: 3,
    HIGH: 2,
    MEDIUM: 1,
    LOW: 0,
  };
  const statusRank = (st: string) => (st === 'active' ? 0 : st === 'offline' ? 1 : st === 'inactive' ? 2 : 3);

  rows.sort((a, b) => {
    let cmp = 0;
    if (sortBy === 'ip') {
      cmp = ipNumericValue(a.ip) - ipNumericValue(b.ip);
    } else if (sortBy === 'status') {
      cmp = statusRank(a.status) - statusRank(b.status) || ipNumericValue(a.ip) - ipNumericValue(b.ip);
    } else if (sortBy === 'hostname') {
      cmp = a.hostname.localeCompare(b.hostname) || ipNumericValue(a.ip) - ipNumericValue(b.ip);
    } else if (sortBy === 'latency') {
      const la = a.latency === null ? Number.MAX_SAFE_INTEGER : a.latency;
      const lb = b.latency === null ? Number.MAX_SAFE_INTEGER : b.latency;
      cmp = la - lb || ipNumericValue(a.ip) - ipNumericValue(b.ip);
    } else if (sortBy === 'ports') {
      cmp = b.openPorts.length - a.openPorts.length || ipNumericValue(a.ip) - ipNumericValue(b.ip);
    } else if (sortBy === 'risk') {
      cmp = riskRank[b.riskLevel] - riskRank[a.riskLevel] || b.highRiskPorts.length - a.highRiskPorts.length || ipNumericValue(a.ip) - ipNumericValue(b.ip);
    }
    return sortDir === 'desc' ? -cmp : cmp;
  });

  const scopeLabelsKo: Record<ReportScope, string> = {
    summary: '핵심 스캔 요약',
    active: '온라인 활성 장비',
    search: searchQuery ? `검색/필터 결과 ("${searchQuery}")` : '현재 필터링 목록',
    all: '전체 서브넷 대역',
    audit: '정밀 보안 감사',
    diff: '스냅샷 변화 비교',
  };
  const scopeLabelsEn: Record<ReportScope, string> = {
    summary: 'Executive Summary',
    active: 'Active Devices',
    search: searchQuery ? `Search Results ("${searchQuery}")` : 'Filtered Devices',
    all: 'Full Subnet Range',
    audit: 'Security Audit',
    diff: 'Snapshot Diff Comparison',
  };

  const activeRatioPct = totalDeviceCount > 0 ? ((activeResults.length / totalDeviceCount) * 100).toFixed(1) : '0.0';
  const scannedCoveragePct = totalDeviceCount > 0 ? Math.min(100, (resolvedScannedIps / totalDeviceCount) * 100).toFixed(1) : '0.0';

  return {
    generatedAt: now.getTime(),
    generatedDateStr: formatLocalDateOnly(now),
    generatedTimeStr: formatLocalTimeOnly(now),
    lang,
    scope,
    scopeLabel: isKo ? scopeLabelsKo[scope] : scopeLabelsEn[scope],
    subnet,
    start,
    end,
    searchQuery,
    branding: effectiveBranding,
    license,
    kpis: {
      totalScannedIpCount: resolvedScannedIps,
      activeDeviceCount: activeResults.length,
      totalDeviceCount,
      inactiveCount: Math.max(0, resolvedScannedIps - activeResults.length),
      activeRatioPct,
      scannedCoveragePct,
      scanStartTimestamp,
      scanEndTimestamp,
      totalScanDurationMs: Math.max(0, totalScanDurationMs),
      isScanning,
      totalOpenPorts,
      highRiskAlertCount: highRiskAlerts.length,
      identifiedVendorsCount: vendorBreakdown.length,
    },
    vendorBreakdown,
    highRiskAlerts,
    diffAnalysis,
    baselineSnapshot: diffAnalysis ? baselineSnapshot : null,
    rows,
    allIps,
    rawResults: results,
  };
}

export function getColumnValue(row: PreparedDeviceRow, col: ReportColumnKey, lang: 'ko' | 'en' = 'ko'): string {
  switch (col) {
    case 'ip':
      return row.ip;
    case 'status':
      return row.status.toUpperCase();
    case 'mac':
      return row.mac;
    case 'vendor':
      return row.vendor;
    case 'chipsetVendor':
      return row.chipsetVendor;
    case 'hostname':
      return row.webTitle ? `${row.hostname} (${row.webTitle})` : row.hostname;
    case 'nameSource':
      return row.nameSource;
    case 'latency':
      return row.latency !== null ? `${row.latency}ms` : '-';
    case 'openPorts':
      return row.openPorts.length > 0 ? row.openPorts.join(', ') : '-';
    case 'deviceType':
      return row.deviceModel ? `${row.deviceType} · ${row.deviceModel}` : row.deviceType;
    case 'os':
      return row.os;
    case 'aliasNotes':
      return row.aliasText;
    case 'riskLevel':
      return row.highRiskPorts.length > 0
        ? `${row.riskLevel} (${row.highRiskPorts.join(',')})`
        : lang === 'ko'
        ? 'LOW'
        : 'LOW';
    default:
      return '-';
  }
}

export function getColumnHeader(col: ReportColumnKey, lang: 'ko' | 'en' = 'ko'): string {
  const meta = REPORT_COLUMNS_META.find((m) => m.key === col);
  if (!meta) return col;
  return lang === 'ko' ? meta.labelKo : meta.labelEn;
}

