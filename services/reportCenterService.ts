export function sanitizeHexColor(color: unknown, fallback = '#0284c7'): string {
  if (typeof color === 'string') {
    const trimmed = color.trim();
    if (/^#[0-9a-fA-F]{6}$/.test(trimmed)) {
      return trimmed.toLowerCase();
    }
  }
  return fallback;
}

export function sanitizeImageDataUrl(url: unknown): string {
  if (typeof url !== 'string') return '';
  const trimmed = url.trim();
  if (/^data:image\/(?:png|jpeg|jpg|webp|gif);base64,[A-Za-z0-9+/=\s]+$/i.test(trimmed)) {
    return trimmed.replace(/\s+/g, '');
  }
  return '';
}

export function getReportBranding(lang: 'ko' | 'en' = 'ko'): ReportBrandingConfig {
  const fallback = getDefaultBranding(lang);
  try {
    const raw = localStorage.getItem(BRANDING_STORAGE_KEY);
    if (!raw) return fallback;
    const parsed = JSON.parse(raw);
    if (!parsed || typeof parsed !== 'object') return fallback;
    const str = (v: unknown, def: string, maxLen = 180) =>
      typeof v === 'string' ? v.slice(0, maxLen) : def;
    const safeLogo = sanitizeImageDataUrl(parsed.logoDataUrl);
    return {
      reportTitle: str(parsed.reportTitle, fallback.reportTitle),
      reportSubtitle: str(parsed.reportSubtitle, fallback.reportSubtitle),
      organizationName: str(parsed.organizationName, fallback.organizationName),
      auditorName: str(parsed.auditorName, fallback.auditorName, 100),
      classificationLabel: str(parsed.classificationLabel, fallback.classificationLabel, 60),
      footerNote: str(parsed.footerNote, fallback.footerNote, 240),
      accentColor: sanitizeHexColor(parsed.accentColor, fallback.accentColor),
      logoDataUrl: safeLogo || undefined,
    };
  } catch {
    return fallback;
  }
}

