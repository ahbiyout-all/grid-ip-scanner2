const MAX_LOGO_FILE_BYTES = 5 * 1024 * 1024;

export async function resizeLogoFileToDataUrl(file: File, maxDim = 160): Promise<string> {
  return new Promise((resolve, reject) => {
    if (!file.type.startsWith('image/')) {
      reject(new Error('Image file required'));
      return;
    }
    if (file.size > MAX_LOGO_FILE_BYTES) {
      reject(new Error('Logo image exceeds 5MB limit'));
      return;
    }
    const reader = new FileReader();
    reader.onerror = () => reject(new Error('Failed to read image file'));
    reader.onload = () => {
      const img = new Image();
      img.onerror = () => reject(new Error('Invalid image format'));
      img.onload = () => {
        try {
          const canvas = document.createElement('canvas');
          const ratio = Math.min(1, maxDim / Math.max(img.width || 1, img.height || 1));
          canvas.width = Math.max(1, Math.round((img.width || maxDim) * ratio));
          canvas.height = Math.max(1, Math.round((img.height || maxDim) * ratio));
          const ctx = canvas.getContext('2d');
          if (!ctx) {
            reject(new Error('Canvas 2D context unavailable'));
            return;
          }
          ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
          const pngDataUrl = canvas.toDataURL('image/png', 0.92);
          const safeUrl = sanitizeImageDataUrl(pngDataUrl);
          if (!safeUrl) {
            reject(new Error('Unsupported logo image output'));
            return;
          }
          resolve(safeUrl);
        } catch (err) {
          reject(err);
        }
      };
      img.src = String(reader.result);
    };
    reader.readAsDataURL(file);
  });
}

